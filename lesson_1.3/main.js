/**
 * Toán tử số học
 * + --> Phép cộng
 * - --> Phép trừ
 * * --> Phép nhân
 * ** --> Phép lũy thừa
 * / --> Phép chia
 * % --> Phép chia lấy dư
 * ++ --> Tăng 1 giá trị số
 * -- --> Giảm 1 giá trị số
 */

var a = 8;
var b = 2;

var c = a + b;
console.log(c);

var c = a - b;
console.log(c);

var c = a ** b;
console.log(c);

var c = a / b;
console.log(c);

var c = a % b;
console.log(c);

var c = ++a;
console.log(c);

var c = --a;
console.log(c);