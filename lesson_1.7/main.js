/**
 * Toán tử so sánh
 * Toán tử
 * ==       -> bằng
 * !=       -> không bằng
 * >        -> Lớn hơn
 * <        -> Nhỏ hơn
 * >=       -> lớn hơn hoặc bằng
 * <=       -> nhỏ hơn hoặc bằng
 */

var a = 2;
var b = 2;
if (a <= b) {
  console.log("Dieu kien dung!");
} else {
  console.log("Dieu kien sai!");
}

